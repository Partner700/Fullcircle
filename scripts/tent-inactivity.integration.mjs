import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { PGlite } from '@electric-sql/pglite';

const db = new PGlite();
await db.exec(`create role anon; create role authenticated; create schema private;
create table profiles(id integer primary key, current_streak int default 0);
create table tent_members(id int primary key, user_id int references profiles(id), role text, joined_at timestamptz);
create table streak_forward_daily_states(user_id int, record_date date, settled boolean, current_streak int, protected boolean, outcome text, primary key(user_id,record_date));
create table protection(user_id int, record_date date);
create function public.compute_strict_streak(int) returns table(current_streak int) language sql as $$select p.current_streak from public.profiles p where p.id=$1$$;
create function public.streak_day_is_protected(int,date) returns boolean language sql as $$select exists(select 1 from public.protection p where p.user_id=$1 and p.record_date=$2)$$;
create temp table test_clock as select timezone('Africa/Douala',now())::date - case when timezone('Africa/Douala',now())::time < time '21:00' then 1 else 0 end as last_day;
insert into profiles select n, case when n=8 then 12 else 0 end from generate_series(1,10) n;
insert into tent_members select n,n,case when n=6 then 'sentry' else 'cadet' end,(c.last_day - case when n=5 then 2 else 30 end)::timestamp at time zone 'Africa/Douala' from generate_series(1,10) n cross join test_clock c where n<>10;
insert into streak_forward_daily_states select n,c.last_day-i,true,0,false,'missed' from generate_series(1,10) n cross join generate_series(0,4) i cross join test_clock c;
update streak_forward_daily_states set current_streak=1,outcome='earned' where user_id=2 and record_date=(select last_day-3 from test_clock);
update streak_forward_daily_states set protected=true,outcome='frozen' where user_id=3 and record_date=(select last_day-2 from test_clock);
delete from streak_forward_daily_states where user_id=4 and record_date=(select last_day-1 from test_clock);
update streak_forward_daily_states set settled=false where user_id=7 and record_date=(select last_day from test_clock);
insert into protection select 9,last_day-2 from test_clock;
`);
await db.exec(readFileSync(new URL('./strengthen-tent-inactivity.sql', import.meta.url), 'utf8'));
assert.equal((await db.query('select count(*)::int n from tent_members')).rows[0].n,9,'install alone must not remove memberships');
assert.equal((await db.query("select has_function_privilege('authenticated','private.drop_inactive_tent_cadets()','execute') access")).rows[0].access,false);
await db.exec('select private.drop_inactive_tent_cadets()');
assert.deepEqual((await db.query('select id from tent_members order by id')).rows.map(x=>x.id),[2,3,4,5,6,7,8,9]);
assert.equal((await db.query('select count(*)::int n from profiles')).rows[0].n,10);
assert.equal((await db.query('select count(*)::int n from streak_forward_daily_states')).rows[0].n,49);
await db.exec('select private.drop_inactive_tent_cadets()');
assert.equal((await db.query('select count(*)::int n from tent_members')).rows[0].n,8);
await db.close();
console.log('Tent inactivity: five settled days, freezer protection, recovery, short/new memberships, sentry exclusion and idempotency passed.');
