game.players[0].score=6;game.players[0].location={route:'main',space:12};game.players[0].prisonTurnsRemaining=2;game.matchDeadline='2026-12-01T17:30:00Z';game.pointsRemaining=17;
const runtime:JourneyRuntime={characterSlug:'david',game,skips:{p1:2},questionIdsByStage:{},usedQuestionIds:[],currentQuestion:null,currentQuestionPlayerId:'p1',questionDeadline:'2026-12-01T17:01:00Z',lastVerdict:null,undo:{playerId:'p1',before:structuredClone(game)}};
