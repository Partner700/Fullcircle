import assert from 'node:assert/strict';
import {buildDuelGroupSchedule,qualifyDuelTents,chooseSpirit,requestSpiritHelp,consumeSpiritHelp,substituteDuelRepresentative,transferDuelJourneySeat,type Duel,type Member} from '../supabase/functions/_shared/interTentDuels.ts';
import {createJourneyGame} from '../supabase/functions/_shared/biblicalJourney.ts';
