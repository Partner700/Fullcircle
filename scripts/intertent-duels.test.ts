assert.equal(substituted.home.representativeId,'p3');
assert.equal(substituted.spirit?.assists,3);
assert.throws(()=>substituteDuelRepresentative(substituted,sentry,{...replacement,userId:'p4'}));
assert.throws(()=>substituteDuelRepresentative(base,witness,replacement));
assert.throws(()=>substituteDuelRepresentative(base,sentry,{...replacement,tentId:'b'}));
