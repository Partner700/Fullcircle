for(const tent of ['a','b','c']) {assert.equal(schedule.filter(f=>f.home===tent).length,4);assert.equal(schedule.filter(f=>f.away===tent).length,4);}
assert.deepEqual(qualifyDuelTents([{tentId:'a',points:8,score:1,answers:1},{tentId:'b',points:6,score:2,answers:1},{tentId:'c',points:4,score:4,answers:1}]),{finalist:'a',semifinal:['b','c']});
