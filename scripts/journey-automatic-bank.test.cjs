const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const read = name => fs.readFileSync(path.join(root, name), 'utf8');
const bank = read('supabase/migrations/20261022091310_journey_automatic_question_bank.sql');
const reset = read('supabase/migrations/20261022091508_journey_reset_question_bank.sql');
const installer = read('scripts/install-journey-question-bank.sql');
assert.match(bank, /ntile\(5\)/);
assert.match(bank, /v_count >= 200/);
assert.match(bank, /'stage', 1/);
assert.match(bank, /SQLSTATE 'P0001' OR data_exception OR integrity_constraint_violation/);
assert.match(bank, /REVOKE ALL ON SCHEMA journey_private FROM PUBLIC, anon, authenticated/);
assert.equal((bank.match(/PERFORM journey_private.require_instructor\(\)/g) || []).length, 4);
assert.match(reset, /DELETE FROM public.arena_journey_questions;/);
assert.doesNotMatch(reset, /TRUNCATE|CASCADE|DELETE FROM public\.(?!arena_journey_questions)/);
assert.match(reset, /r\.status = 'playing'/);
assert.match(reset, /SET current_question_id = NULL/);
assert.match(installer, /pg_advisory_xact_lock/);
assert.match(installer, /\\if :reset_completed/);
assert.match(installer, /\\if :rehearse[\s\S]*ROLLBACK;[\s\S]*\\else[\s\S]*COMMIT;/);
console.log('Automatic Journey bank and one-time reset safety checks passed.');
