import assert from 'node:assert/strict';
import { createJourneyGame, DEFAULT_JOURNEY_CONFIG, JOURNEY_TRAP_LIBRARY, journeyScore, resolveJourneyAction, resolveJourneyMiss, resolveJourneyRoll } from '../supabase/functions/_shared/biblicalJourney.ts';
import { answerJourneyQuestion, createJourneyRuntime, publicJourneyRuntime, rollJourneyDie, applyJourneyRelic, type JourneyQuestion } from '../supabase/functions/_shared/biblicalJourneyRuntime.ts';
import { applyRoadHomeCommand, createRoadHomeGame, publicRoadHomeState } from '../supabase/functions/_shared/road-home-engine.ts';
import { arenaPlayerScore } from '../src/lib/arenaScorecard.ts';

const plain = { ...DEFAULT_JOURNEY_CONFIG, traps: {}, loopEntrances: [20, 26] as [number,number] };
let game = createJourneyGame(['alpha','beta']);
game = resolveJourneyRoll(game,'alpha',6,plain);
assert.equal(game.turnIndex,0);
assert.equal(game.events.at(-1)?.effectType,'extra-turn');
game = resolveJourneyRoll(game,'alpha',6,plain);
assert.equal(game.turnIndex,0);
game = resolveJourneyMiss(game,'alpha',6);
assert.equal(game.turnIndex,0);
assert.equal(resolveJourneyMiss(game,'alpha',3).turnIndex,1);
game = createJourneyGame(['alpha','beta']);
game.players[0].location = {route:'loop',space:1};
game.players[0].status = 'TRAPPED_IN_LOOP';
game = resolveJourneyRoll(game,'alpha',6,plain);
assert.equal(game.turnIndex,0);
assert.equal(journeyScore(game.players[0]),0);

const sixTrial = {...plain,traps:{7:JOURNEY_TRAP_LIBRARY.final_trial}};
game = resolveJourneyRoll(createJourneyGame(['alpha','beta']),'alpha',6,sixTrial);
assert.equal(game.pendingAction?.kind,'trial');
assert.equal(resolveJourneyAction(game,'alpha',0,sixTrial).turnIndex,0);
const prison = resolveJourneyAction(game,'alpha',1,sixTrial);
assert.equal(prison.turnIndex,1);
assert.equal(prison.players[0].prisonTurnsRemaining,3);
assert.equal(prison.bonusTurnPlayerId,null);
assert.equal(resolveJourneyRoll(createJourneyGame(['alpha','beta']),'alpha',6,
  {...plain,traps:{7:JOURNEY_TRAP_LIBRARY.captured}}).turnIndex,1);

game = createJourneyGame(['alpha','beta']);
game.players[0].correctAnswers=10;
game.players[0].location={route:'main',space:15};
const back = resolveJourneyRoll(game,'alpha',1,{...plain,traps:{16:JOURNEY_TRAP_LIBRARY.seven_behind}});
assert.equal(back.players[0].correctAnswers,11);
assert.equal(journeyScore(back.players[0]),4);
assert.deepEqual(back.players[0].location,{route:'main',space:9});
const clamped = resolveJourneyRoll(createJourneyGame(['alpha','beta']),'alpha',2,
  {...plain,traps:{3:JOURNEY_TRAP_LIBRARY.great_fall}});
assert.equal(journeyScore(clamped.players[0]),-1,'only two actual backward steps, not twenty');
const collective = resolveJourneyRoll(createJourneyGame(['alpha','beta']),'alpha',6,
  {...plain,traps:{7:JOURNEY_TRAP_LIBRARY.collective_fall}});
assert.equal(journeyScore(collective.players[0]),-4,'collective effect charged once');
assert.equal(journeyScore(collective.players[1]),0,'no steps at Start');
assert.equal(arenaPlayerScore({correct_count:11,score:-4}),-4);
game.players[0].location={route:'main',space:43};
assert.equal(journeyScore(resolveJourneyRoll(game,'alpha',4,plain).players[0]),11,'forward lap wrap is not a penalty');
game.players[0].completedLaps=1;
assert.equal(resolveJourneyRoll(game,'alpha',6,plain).status,'finished','win ends the match even on six');

const catalog: JourneyQuestion[] = Array.from({length:200},(_,index)=>({id:`q${index}`,stage:Math.floor(index/40)+1,type:'multiple_choice',question:'Who built the ark?',options:['Noah','Moses','David','Elisha'],correctAnswer:'Noah',acceptedAnswers:[],reference:'Genesis 6',explanation:'Noah built it.'}));
const lookup=async(id:string)=>catalog.find(q=>q.id===id)||null;
const start=await createJourneyRuntime('elisha',['alpha','beta'],catalog,lookup,()=>0);
const open=rollJourneyDie(start,'alpha',()=>.99);
open.questionOpensAt=new Date(Date.now()-1).toISOString();
await assert.rejects(()=>applyJourneyRelic(open,'beta','hint',lookup,()=>0),/only during/);
await assert.rejects(()=>applyJourneyRelic(start,'alpha','hint',lookup,()=>0),/only during/);
await assert.rejects(()=>applyJourneyRelic(open,'alpha','lazarus-coin',lookup,()=>0),/not used/);
let state=await applyJourneyRelic(open,'alpha','freeze-timer',lookup,()=>0);
assert.equal(Date.parse(state.questionDeadline!)-Date.parse(open.questionDeadline!),60000);
await assert.rejects(()=>applyJourneyRelic(state,'alpha','freeze-timer',lookup,()=>0),/already used/);
state=await applyJourneyRelic(state,'alpha','eliminate',lookup,()=>0);
assert.deepEqual(state.questionAid?.hiddenOptions,['Moses','David']);
assert.equal(JSON.stringify(publicJourneyRuntime(state)).includes('Noah built it.'),false);
state=await applyJourneyRelic(state,'alpha','talking-donkey',lookup,()=>0);
state=await answerJourneyQuestion(state,'alpha','Moses',lookup,()=>0);
assert.equal(state.currentQuestion?.id,open.currentQuestion?.id);
assert.equal(state.questionAid?.donkeyActive,false);
state=await answerJourneyQuestion(state,'alpha','Moses',lookup,()=>0);
assert.equal(state.awaitingRoll,true);
assert.equal(state.game.turnIndex,0,'six bonus survives an incorrect answer');
const skip=await applyJourneyRelic(open,'alpha','skip',lookup,()=>0);
assert.equal(skip.game.players[0].correctAnswers,0);
assert.equal(skip.lastVerdict?.selectedAnswer,'Skipped');
const crystal=await applyJourneyRelic(open,'alpha','witch-ball-endor',lookup,()=>0);
assert.equal(crystal.lastVerdict?.correct,true);
assert.equal(crystal.game.players[0].correctAnswers,1);
assert.equal(crystal.questionAid,undefined);
const expired=structuredClone(open); expired.questionDeadline=new Date(Date.now()-1).toISOString();
await assert.rejects(()=>applyJourneyRelic(expired,'alpha','hint',lookup,()=>0),/only during/);
const hint=await applyJourneyRelic(open,'alpha','hint',lookup,()=>0);
assert.match(hint.questionAid!.notice,/Genesis 6/);
const reference=await applyJourneyRelic(open,'alpha','reveal-reference',lookup,()=>0);
assert.equal(reference.questionAid!.notice,'Reference: Genesis 6');
const staleVerdict=structuredClone(open); staleVerdict.lastVerdict=crystal.lastVerdict;
assert.equal((await applyJourneyRelic(staleVerdict,'alpha','hint',lookup,()=>0)).lastVerdict,null,
  'a relic must not reopen the preceding verdict');

let ludo=createRoadHomeGame('room',[{id:'alpha',name:'A'},{id:'beta',name:'B'}],[],()=>.5);
ludo.players[0].pawns[0].progress=0;
ludo=applyRoadHomeCommand(ludo,'alpha',{action:'ROLL'},[],()=>.3);
const deadline=ludo.questionDeadline!;
ludo=applyRoadHomeCommand(ludo,'alpha',{action:'USE_MARKET_RELIC',slug:'freeze-timer'},[],()=>0);
