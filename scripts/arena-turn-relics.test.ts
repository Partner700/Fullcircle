assert.throws(()=>applyRoadHomeCommand(ludo,'alpha',{action:'USE_MARKET_RELIC',slug:'freeze-timer'},[],()=>0),/already used/);
ludo=applyRoadHomeCommand(ludo,'alpha',{action:'USE_MARKET_RELIC',slug:'talking-donkey'},[],()=>0);
ludo=applyRoadHomeCommand(ludo,'alpha',{action:'ANSWER',answer:'wrong'},[],()=>0);
