import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
if (!process.env.PGLITE_MODULE) throw new Error('Set PGLITE_MODULE to a test-only PGlite installation.');
const { PGlite } = await import(process.env.PGLITE_MODULE);
const db = new PGlite();
const migration = await readFile(new URL('../supabase/migrations/20261022170055_restore_app_storage_policies.sql', import.meta.url), 'utf8');
const cadet = '10000000-0000-4000-8000-000000000001';
const other = '10000000-0000-4000-8000-000000000002';
const instructor = '10000000-0000-4000-8000-000000000003';
const as = async (id, role='authenticated') => {
  await db.exec('RESET ROLE');
  await db.query("SELECT set_config('request.jwt.claim.sub',$1,false)", [id || '']);
  await db.exec(`SET ROLE ${role}`);
};
const write = (name, bucket='avatars') => db.query('INSERT INTO storage.objects(bucket_id,name,metadata) VALUES($1,$2,$3)',[bucket,name,'{"version":1}']);
const upsert = (name) => db.query("INSERT INTO storage.objects(bucket_id,name,metadata) VALUES('avatars',$1,'{\"version\":2}') ON CONFLICT(bucket_id,name) DO UPDATE SET metadata=EXCLUDED.metadata RETURNING name",[name]);
try {
  await db.exec(`
    CREATE ROLE anon; CREATE ROLE authenticated;
    CREATE SCHEMA auth; CREATE SCHEMA storage;
    GRANT USAGE ON SCHEMA auth, public TO anon, authenticated;
    CREATE FUNCTION auth.uid() RETURNS uuid LANGUAGE sql STABLE AS $$ SELECT nullif(current_setting('request.jwt.claim.sub',true),'')::uuid $$;
    CREATE TABLE public.role_assignments(user_id uuid,role text,status text);
    CREATE FUNCTION public.is_instructor(id uuid) RETURNS boolean LANGUAGE sql STABLE SECURITY DEFINER SET search_path='' AS $$
      SELECT EXISTS(SELECT 1 FROM public.role_assignments WHERE user_id=id AND role='instructor' AND status IN ('active','approved')) $$;
    INSERT INTO public.role_assignments VALUES('${instructor}','instructor','active');
    CREATE TABLE storage.buckets(id text PRIMARY KEY,public boolean,file_size_limit bigint,allowed_mime_types text[]);
    INSERT INTO storage.buckets VALUES('avatars',true,26214400,NULL),('private',false,1024,ARRAY['image/png']);
    CREATE TABLE storage.objects(bucket_id text,name text,metadata jsonb,UNIQUE(bucket_id,name));
    ALTER TABLE storage.objects ENABLE ROW LEVEL SECURITY;
    CREATE FUNCTION storage.foldername(name text) RETURNS text[] LANGUAGE sql IMMUTABLE AS $$ SELECT string_to_array(name,'/') $$;
    INSERT INTO storage.objects VALUES('avatars','${other}/avatar-existing.webp','{"version":0}'),('private','secret.png','{}');
  `);
  await as(cadet);
  await assert.rejects(write(`${cadet}/avatar-before.webp`), /permission denied/);
  await db.exec('RESET ROLE; GRANT USAGE ON SCHEMA storage TO authenticated; GRANT SELECT, INSERT, UPDATE, DELETE ON storage.objects TO authenticated;');
  await as(cadet);
  await assert.rejects(write(`${cadet}/avatar-before.webp`), /row-level security/);
  await db.exec('RESET ROLE');
  const initialBuckets = (await db.query('SELECT * FROM storage.buckets ORDER BY id')).rows;
  await db.exec('BEGIN');
  await db.exec(migration);
  await db.exec('ROLLBACK');
  assert.equal((await db.query("SELECT count(*)::int n FROM pg_policies WHERE schemaname='storage'")).rows[0].n,0,'rehearsal rolls back policies');
  await db.exec("CREATE POLICY retained_other_policy ON storage.objects FOR SELECT TO authenticated USING (bucket_id='reserved')");
  await db.exec(migration);
  assert.equal((await db.query("SELECT count(*)::int n FROM pg_policies WHERE schemaname='storage' AND policyname='retained_other_policy'")).rows[0].n,1,'unrelated policies remain intact');
  await db.exec(migration);
  assert.deepEqual((await db.query('SELECT * FROM storage.buckets ORDER BY id')).rows,initialBuckets,'existing bucket settings are preserved');
  assert.equal((await db.query('SELECT count(*)::int n FROM storage.objects')).rows[0].n,2,'no existing file metadata is touched');
  await as(cadet);
  const avatar = `${cadet}/avatar-new.webp`;
  await write(avatar);
  assert.equal((await upsert(avatar)).rows.length,1,'current app upsert can replace an owned object');
  await write(`${cadet}/fcx/event/guest.webp`);
  await write(`${cadet}/challenge-evidence/proof.webp`);
  await assert.rejects(write(`${other}/avatar-new.webp`),/row-level security/);
  await assert.rejects(upsert(`${other}/avatar-existing.webp`),/row-level security/);
  await assert.rejects(write('panel-images/picture.webp'),/row-level security/);
  await assert.rejects(write('weekly-backgrounds/picture.webp'),/row-level security/);
  await assert.rejects(write('avatar-no-owner.webp'),/row-level security/);
  await assert.rejects(write(`${cadet}/avatar.webp`,'private'),/row-level security/);
  assert.equal((await db.query("SELECT * FROM storage.objects WHERE bucket_id='private'")).rows.length,0);
  await assert.rejects(db.query('UPDATE storage.objects SET name=$1 WHERE name=$2',[`${other}/stolen.webp`,avatar]),/row-level security/);
  assert.equal((await db.query('DELETE FROM storage.objects WHERE name=$1 RETURNING name',[`${other}/avatar-existing.webp`])).rows.length,0);
  assert.equal((await db.query('DELETE FROM storage.objects WHERE name=$1 RETURNING name',[avatar])).rows.length,1);
  await as(null,'anon');
  await assert.rejects(write(`${cadet}/anonymous.webp`),/permission denied|row-level security/);
  assert.ok((await db.query("SELECT * FROM storage.objects WHERE bucket_id='avatars'")).rows.length > 0);
  await as(null);
  await assert.rejects(write(`${cadet}/no-session.webp`),/row-level security/);
  await as(instructor);
  await write('panel-images/picture.webp');
  await upsert('panel-images/picture.webp');
  await write('weekly-backgrounds/picture.webp');
  await assert.rejects(write(`${other}/instructor-overwrite.webp`),/row-level security/);
  await assert.rejects(write('unrelated/picture.webp'),/row-level security/);
  await db.exec('RESET ROLE');
  await db.query("UPDATE public.role_assignments SET status='expired' WHERE user_id=$1",[instructor]);
  await as(instructor);
  await assert.rejects(write('panel-images/expired.webp'),/row-level security/);
  await db.exec('RESET ROLE');
  assert.deepEqual((await db.query('SELECT metadata FROM storage.objects WHERE name=$1',[`${other}/avatar-existing.webp`])).rows[0].metadata,{version:0});
  console.log('Photo storage checks passed: missing-policy reproduction, rollback, repeatable repair, own-folder upload/upsert, shared instructor images, cross-account and anonymous denial, unchanged existing files.');
} catch (error) {
  console.error(error.message, error.where || '');
  process.exitCode = 1;
} finally { await db.close(); }
