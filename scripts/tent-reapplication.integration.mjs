import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { PGlite } from '@electric-sql/pglite';

const db = new PGlite();
const id = n => `00000000-0000-4000-8000-${String(n).padStart(12,'0')}`;
const [former,newcomer,qualified,other,first,second] = [1,2,3,4,11,12].map(id);
await db.exec(`create role anon; create role authenticated; create schema private; create schema auth; create schema camp_management;
create function auth.uid() returns uuid language sql as $$select nullif(current_setting('test.uid',true),'')::uuid$$;
create function camp_management.is_admin() returns boolean language sql as $$select false$$;
create table profiles(id uuid primary key, longest_streak int);
create table private.resident_tent_trials(user_id uuid primary key);
create table subscriptions(user_id uuid primary key,status text,trial_started_at timestamptz,trial_ends_at timestamptz,current_period_end timestamptz,updated_at timestamptz);
create table tents(id uuid primary key,name text,profile_image_url text,camp_id int);
create table tent_members(user_id uuid,tent_id uuid,role text);
create table tent_join_requests(user_id uuid,tent_id uuid,status text default 'pending');
create unique index one_pending on tent_join_requests(user_id,tent_id) where status='pending';
create table role_assignments(user_id uuid,role text,status text);
create function public.compute_strict_streak(uuid) returns table(longest_streak int) language sql as $$select p.longest_streak from public.profiles p where p.id=$1$$;
create function public.has_current_subscription_access(uuid) returns boolean language sql as $$select exists(select 1 from public.subscriptions s where s.user_id=$1 and (s.status='active' or (s.status='trial' and s.trial_ends_at>now())))$$;
create function public.tent_cadet_count(uuid) returns int language sql as $$select count(*)::int from public.tent_members where tent_id=$1 and role='cadet'$$;
create function public.tent_cadet_limit(uuid) returns int language sql as $$select 10$$;
insert into profiles values ('${former}',0),('${newcomer}',4),('${qualified}',5),('${other}',5);
insert into private.resident_tent_trials values ('${former}');
insert into subscriptions(user_id,status) values ('${former}','expired');
insert into role_assignments values ('${former}','cadet','active'),('${newcomer}','cadet','active'),('${qualified}','cadet','active'),('${other}','cadet','active');
insert into tents values ('${first}','First',null,1),('${second}','Second',null,1),('${id(13)}','Other camp',null,2);`);
await db.exec(readFileSync(new URL('./tent-reapplication.sql', import.meta.url),'utf8'));
await db.exec(`create trigger eligibility_request before insert on tent_join_requests for each row execute function public.enforce_resident_tent_eligibility();
create trigger eligibility_member before insert on tent_members for each row execute function public.enforce_resident_tent_eligibility();`);
const run = (sql, params=[]) => db.query(sql,params);
const actor = u => run("select set_config('test.uid',$1,false)",[u]);
await actor(former);
assert.equal((await run('select * from public.get_tent_join_options()')).rows.length,2);
await run('insert into tent_join_requests(user_id,tent_id) values ($1,$2),($1,$3)',[former,first,second]);
assert.ok((await run('select * from public.get_tent_join_options()')).rows.every(r=>r.requested));
await assert.rejects(run("insert into tent_members values ($1,$2,'cadet')",[former,first]),/active subscription/);
assert.equal((await run('select status from subscriptions where user_id=$1',[former])).rows[0].status,'expired');
await run("update subscriptions set status='active' where user_id=$1",[former]);
await run("insert into tent_members values ($1,$2,'cadet')",[former,first]);
assert.equal((await run('select * from public.get_tent_join_options()')).rows.length,0);
await actor(newcomer);
assert.equal((await run('select * from public.get_tent_join_options()')).rows.length,0);
await assert.rejects(run('insert into tent_join_requests(user_id,tent_id) values ($1,$2)',[newcomer,first]),/5-day streak/);
await actor(qualified);
assert.equal((await run('select * from public.get_tent_join_options()')).rows.length,2);
await run('insert into tent_join_requests(user_id,tent_id) values ($1,$2)',[qualified,second]);
await run("insert into tent_members values ($1,$2,'cadet')",[qualified,second]);
assert.equal((await run('select status from subscriptions where user_id=$1',[qualified])).rows[0].status,'trial');
assert.equal((await run("select has_function_privilege('anon','public.get_tent_join_options()','execute') as permitted")).rows[0].permitted,false);
await db.close();
console.log('Tent reapplication: former zero-streak and expired members may apply to multiple tents, paid re-entry and first-time streak requirements preserved.');
